/**
 * 글 본문(모델이 쓴 마크다운)의 역슬래시를 글자 그대로 보이게 한다.
 *
 * 마크다운에서 역슬래시는 "다음 글자를 서식이 아니라 글자로 보여라"는 표시라서 화면에
 * 나오지 않는다. 그런데 모델은 역슬래시를 그 기호 자체를 말하려고 쓴다 — lie-detective
 * 10/10 글의 "역슬래시(\)"가 화면에 "역슬래시()"로 나갔다. 역슬래시가 뒤의 괄호를
 * 글자로 만드는 데 쓰이고 사라진 것이다 (10/11).
 *
 * 코드(`…`, ``` 블록) 밖의 역슬래시를 두 개로 바꿔 한 개가 그대로 보이게 한다. 코드 안은
 * 원래 글자 그대로 나오므로 건드리지 않는다. 글 페이지와 서식 검사기가 같이 쓴다 —
 * 검사기가 화면과 다른 눈으로 읽으면 없는 문제를 보고하거나 있는 문제를 놓친다.
 */
export function keepBackslashes(md: string): string {
  return md
    .split(/(```[\s\S]*?```|`[^`\n]*`)/)
    .map((part, i) => (i % 2 === 1 ? part : part.replace(/\\/g, "\\\\")))
    .join("");
}
