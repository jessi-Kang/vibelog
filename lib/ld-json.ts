/**
 * JSON-LD를 `<script>` 안에 넣을 때 쓰는 한 곳.
 *
 * `JSON.stringify`는 **`<`를 이스케이프하지 않는다.** 그래서 값에 `</script>`가
 * 들어 있으면 브라우저가 거기서 태그를 닫고 그 뒤를 마크업으로 읽는다 — 문자열
 * 하나로 스크립트 이탈(XSS)이 된다.
 *
 * 이 사이트에서 이게 이론이 아닌 이유: 글의 제목·요약은 **모델이 쓰고 사람이
 * 읽기 전에 발행된다.** 원료는 커밋 메시지다. 중간에 사람이 걸러 준다는 가정을
 * 둘 수 없으므로, 값을 믿는 대신 넣는 자리를 막는다.
 *
 * 재현 (레드팀 검사에서 실제로 확인했다):
 *   제목에 `x</script><img src=x onerror=...>`를 넣으면 그 글 페이지의 HTML이
 *   ld+json 블록 한가운데서 닫히고 img가 DOM에 붙는다.
 *
 * `<`는 JSON 문자열 안에서 `<`와 같은 값이라 구조화 데이터의 뜻은 그대로다.
 * U+2028/2029도 함께 막는다 — 자바스크립트 문자열에서 줄바꿈으로 읽힌다.
 */
export function ldJson(data: unknown): string {
  return JSON.stringify(data)
    .replace(/</g, "\\u003c")
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029");
}
